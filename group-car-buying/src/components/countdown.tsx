"use client";

import { useEffect, useState } from "react";

export function formatRemaining(ms: number): string {
  if (ms <= 0) return "ended";
  const d = Math.floor(ms / 86_400_000);
  const h = Math.floor((ms % 86_400_000) / 3_600_000);
  const m = Math.floor((ms % 3_600_000) / 60_000);
  if (d > 0) return `${d}d ${h}h left`;
  if (h > 0) return `${h}h ${m}m left`;
  return `${Math.max(1, m)}m left`;
}

export function Countdown({ to, className }: { to: string | Date; className?: string }) {
  const target = new Date(to).getTime();
  const [now, setNow] = useState<number | null>(null);
  useEffect(() => {
    setNow(Date.now());
    const t = setInterval(() => setNow(Date.now()), 30_000);
    return () => clearInterval(t);
  }, []);
  // Render nothing time-dependent on the server to avoid hydration mismatches.
  return <span className={className} suppressHydrationWarning>{now === null ? "…" : formatRemaining(target - now)}</span>;
}
